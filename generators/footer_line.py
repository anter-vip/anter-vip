"""
footer_line.py — thin animated cyan rule + the daily generation stamp.
A light dot travels the line via <animateMotion>; the line itself is a
static gradient (opacity pulse). Date is injected by the workflow with sed,
falls back to today's date on local runs.
"""

from __future__ import annotations

import datetime
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from common import (  # noqa: E402
    BG, CYAN, VIOLET, FAINT, WIDTH,
    Svg,
)

H = 60


def build() -> str:
    svg = Svg(WIDTH, H, title="footer")
    svg.el(f'<rect width="{WIDTH}" height="{H}" fill="{BG}"/>')
    grad = svg.lg([(0.0, "#050505"), (0.45, CYAN), (0.6, VIOLET), (1.0, "#050505")])
    y = 20
    svg.el(
        f'<line x1="60" y1="{y}" x2="{WIDTH - 60}" y2="{y}" stroke="{grad}"'
        f' stroke-width="1.4">'
        f'<animate attributeName="opacity" values="0.5;1;0.5" dur="4s"'
        f' repeatCount="indefinite"/></line>'
    )
    # traveling photon
    svg.el(
        f'<circle r="2.6" fill="{CYAN}">'
        f'<animateMotion path="M 60 {y} L {WIDTH - 60} {y}" dur="7s"'
        f' repeatCount="indefinite"/>'
        f'<animate attributeName="opacity" values="0;1;1;0"'
        f' keyTimes="0;0.08;0.92;1" dur="7s" repeatCount="indefinite"/></circle>'
    )
    date = os.environ.get("GEN_DATE", datetime.date.today().isoformat())
    svg.el(svg.text(WIDTH / 2, H - 18,
                    f"// last generated by GitHub Actions · {date} · deterministic art",
                    10, FAINT, anchor="middle", spacing=1))
    return svg.tostring()


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "assets", "footer.svg")
    with open(out, "w") as f:
        f.write(build())
    print(f"wrote {out} ({os.path.getsize(out) / 1024:.1f} KB)")
